#ifndef GUARD_CONFIG_SHATTERED_H
#define GUARD_CONFIG_SHATTERED_H

// Build-time settings. No persistent structure or stored EXP tables change.
// Expanded move pages currently require unlimited PP.
#define SHATTERED_NORMAL 0
#define SHATTERED_HARD 1
#define SHATTERED_EXTREME 2

#ifndef SHATTERED_DIFFICULTY
#define SHATTERED_DIFFICULTY SHATTERED_EXTREME
#endif
#ifndef SHATTERED_LEVEL_SCALING
#define SHATTERED_LEVEL_SCALING (SHATTERED_DIFFICULTY != SHATTERED_NORMAL)
#endif
#ifndef SHATTERED_ENHANCED_AI
#define SHATTERED_ENHANCED_AI (SHATTERED_DIFFICULTY != SHATTERED_NORMAL)
#endif
#ifndef SHATTERED_UNLIMITED_PP
#define SHATTERED_UNLIMITED_PP TRUE
#endif
#ifndef SHATTERED_EXPANDED_MOVES
#define SHATTERED_EXPANDED_MOVES SHATTERED_UNLIMITED_PP
#endif
#ifndef SHATTERED_EXP_MULTIPLIER
#define SHATTERED_EXP_MULTIPLIER 4
#endif
#ifndef SHATTERED_UNLIMITED_MONEY
#define SHATTERED_UNLIMITED_MONEY TRUE
#endif
#ifndef SHATTERED_FREE_SUPPLIES
#define SHATTERED_FREE_SUPPLIES TRUE
#endif

#if SHATTERED_DIFFICULTY < SHATTERED_NORMAL || SHATTERED_DIFFICULTY > SHATTERED_EXTREME
#error Invalid Shattered Realms difficulty
#endif
#if SHATTERED_EXP_MULTIPLIER < 1 || SHATTERED_EXP_MULTIPLIER > 4
#error Shattered Realms EXP multiplier must be between 1 and 4
#endif
#if SHATTERED_EXPANDED_MOVES && !SHATTERED_UNLIMITED_PP
#error Expanded move pages require unlimited PP
#endif

#endif
